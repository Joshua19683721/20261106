function buildCharset() {
  const set = new Set();
  const add = s => { for (const ch of String(s)) if (/\p{Script=Han}/u.test(ch)) set.add(ch); };
  LESSONS.forEach(L => { add(L.chars); L.words.forEach(add); L.lines.forEach(add); });
  META_WORDS.forEach(add);
  FUNCTION_WORDS.forEach(add);
  EXAM_WORDS.forEach(add);
  ACTIVITY_WORDS.forEach(add);
  return set;
}

function buildWordset() {
  const set = new Set();
  LESSONS.forEach(L => { L.words.forEach(w => set.add(w)); w => 0; });
  META_WORDS.forEach(w => set.add(w));
  return set;
}

